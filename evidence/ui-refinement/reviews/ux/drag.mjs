import { chromium, base, shot } from './lib.mjs';
import { writeFileSync } from 'node:fs';
const b = await chromium.launch();
const res = {};
const c = await b.newContext({ viewport: { width: 1280, height: 800 } });
const page = await c.newPage();
const st = () => page.evaluate(() => ({ state: document.querySelector('.waambat-cursor').dataset.cursorState, op: document.querySelector('.waambat-cursor').style.opacity, root: document.documentElement.dataset.waambatCursor || null }));
await page.goto(base + '/', { waitUntil: 'load' }); await page.waitForTimeout(1800);
const img = page.locator('main img').nth(2); await img.scrollIntoViewIfNeeded(); await page.waitForTimeout(300); const bb = await img.boundingBox();
await page.mouse.move(bb.x + 60, bb.y + 60, { steps: 3 }); await page.waitForTimeout(150);
res.overArt = await st();
await shot(page, 'cursor-over-art', { clip: { x: bb.x, y: bb.y, width: 160, height: 140 } });
await page.mouse.down(); await page.waitForTimeout(80); res.pressedOverArt = await st();
await page.mouse.move(bb.x + 140, bb.y + 160, { steps: 10 }); await page.waitForTimeout(150);
res.duringDrag = await st();
await page.mouse.up(); await page.waitForTimeout(250);
res.afterDrag = await st();
const rail = page.locator('.waambat-scroll-rail');
const rb = await rail.boundingBox(); res.railBox = rb;
const thumbY = await page.evaluate(() => { const r = document.querySelector('.waambat-scroll-rail').getBoundingClientRect(); const total = document.documentElement.scrollHeight - innerHeight; return r.top + (r.height - Math.max(48, r.height * innerHeight / document.documentElement.scrollHeight)) * (scrollY / total) + 10; });
await page.mouse.move(rb.x + 9, thumbY, { steps: 3 }); await page.waitForTimeout(250);
res.railHover = await st();
await shot(page, 'scroll-rail-hover', { clip: { x: rb.x - 60, y: Math.max(0, thumbY - 100), width: 80, height: 200 } });
await page.mouse.down(); await page.waitForTimeout(80); res.railPressed = await st();
await page.mouse.move(rb.x + 9, thumbY + 150, { steps: 8 }); await page.waitForTimeout(150);
res.railDrag = { ...(await st()), y: await page.evaluate(() => scrollY) };
await shot(page, 'scroll-rail-drag', { clip: { x: rb.x - 60, y: Math.max(0, thumbY), width: 80, height: 260 } });
await page.mouse.up();
// Pressed state over a button holds pointer shape
const btn = page.locator('.media-control').first(); await btn.scrollIntoViewIfNeeded(); const cb = await btn.boundingBox();
await page.mouse.move(cb.x + 22, cb.y + 22, { steps: 3 }); await page.mouse.down(); await page.waitForTimeout(100);
res.pressedButton = await st(); await page.mouse.up();
writeFileSync(new URL('./drag.json', import.meta.url), JSON.stringify(res, null, 2));
console.log(JSON.stringify(res, null, 2));
await b.close();
